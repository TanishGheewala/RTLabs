// Conditional
if statement begin
    something;
end
else if statement begin
    something;
end
else begin
    something;
end

// While Loop
while (condition) begin
    something;
end

// Forever Loop
forever begin
    something;
end

// Repeat Loop
repeat (num_iterations) begin
    something;
end

// For Loop
for (initialization; condition; increment) begin
    something;
end
